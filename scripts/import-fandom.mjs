// Import articles from the Kenshi Fandom wiki (CC BY-SA 3.0) into src/content/wiki as Markdown.
// Usage: node scripts/import-fandom.mjs [--all | title ...]   (no arguments: the built-in test set)
// Responses are cached in .fandom-cache/, so re-running only re-converts. Images are not imported.
import * as cheerio from 'cheerio';
import TurndownService from 'turndown';
import { slug as headingSlug } from 'github-slugger';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync, readdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { pageSlug } from '../src/lib/wiki.js';

const api = 'https://kenshi.fandom.com/api.php';
const userAgent = 'kenshi-wiki-import (https://github.com/mattresspad/kenshi-wiki)';
const cacheDir = '.fandom-cache';
const outDir = 'src/content/wiki';
const redirectsFile = 'public/_redirects';
const redirectsStart = '# Fandom import: redirects below are generated by scripts/import-fandom.mjs';

const testSet = [
  'The Holy Nation', 'Shek Kingdom', 'Tech Hunters',
  'The Hub', 'Squin', "World's End",
  'Shek', 'Hive', 'Skeleton',
  'Border Zone', 'Beak Thing', 'Bonedog',
  'Beep', 'Ruka', 'Holy Lord Phoenix',
  'Nodachi', 'Samurai Armour', 'Hashish',
  'Skills', 'Toughness',
  // Titles that exercise the URL mapping: a subpage, a namespace-style colon, and reserved characters.
  'Admag/Berserkers', 'Kenshi:Lua', 'Wheatstraw 60% or Cactus 100%?',
];

// Fandom chrome, media and navigation that the wiki does not carry over.
const removed = [
  'script', 'style', 'noscript', 'figure', 'img', '.thumb', '.gallery', '.wikia-gallery', '.mw-editsection', '.toc',
  'table.navbox', '.navbox', '.navbar', '.printfooter', '.mw-empty-elt',
  '.pi-image', '.info-icon', '[typeof^="mw:File"]', '.mw-default-size', 'a.image', 'a.mw-file-description',
].join(', ');

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function requestApi(params) {
  const response = await fetch(`${api}?${new URLSearchParams({ ...params, format: 'json', formatversion: '2' })}`, {
    headers: { 'User-Agent': userAgent },
  });
  const body = response.ok ? await response.json() : {};
  await sleep(1000);
  return { response, body };
}

// One request a second; network failures, rate limits and server errors are retried with a growing pause.
async function callApi(params) {
  for (let attempt = 1; ; attempt++) {
    const { response, body } = await requestApi(params).catch((error) => ({ error }));
    const transient = !response || response.status === 429 || response.status >= 500;
    if (response?.ok && !body.error) return body;
    if (!transient || attempt === 5) throw new Error(`${JSON.stringify(params)}: ${body?.error?.info ?? response?.status}`);
    await sleep(attempt * 10_000);
  }
}

// Every article on the wiki (not redirects), cached like the pages.
async function allTitles() {
  const cached = `${cacheDir}/_titles.json`;
  if (existsSync(cached)) return JSON.parse(await readFile(cached, 'utf8'));

  const titles = [];
  let next = {};
  do {
    const body = await callApi({ action: 'query', list: 'allpages', apnamespace: '0', apfilterredir: 'nonredirects', aplimit: 'max', ...next });
    titles.push(...body.query.allpages.map((page) => page.title));
    next = body.continue ?? null;
  } while (next);

  await writeFile(cached, JSON.stringify(titles));
  return titles;
}

// The rendered article plus the titles that redirect to it, cached per requested title.
async function fetchPage(title) {
  const cached = `${cacheDir}/${encodeURIComponent(title)}.json`;
  if (existsSync(cached)) return JSON.parse(await readFile(cached, 'utf8'));

  const { parse } = await callApi({
    action: 'parse', page: title, redirects: '1', prop: 'text|categories|revid|displaytitle',
    disableeditsection: '1', disabletoc: '1', disablelimitreport: '1',
  });
  const { query } = await callApi({ action: 'query', titles: parse.title, prop: 'redirects', rdnamespace: '0', rdlimit: 'max' });
  parse.aliases = (query.pages[0].redirects ?? []).map((redirect) => redirect.title);

  await writeFile(cached, JSON.stringify(parse));
  return parse;
}

// A Fandom article link becomes a wiki link; anything else in a wiki namespace is reduced to its text.
function rewriteLink($, link) {
  const href = $(link).attr('href') ?? '';
  if ($(link).hasClass('new') || href.includes('redlink=1') || href.includes('wikia.nocookie.net')) {
    $(link).replaceWith($(link).contents());
    return;
  }

  const match = href.match(/^(?:https?:\/\/kenshi\.fandom\.com)?\/wiki\/([^?#]+)(?:\?[^#]*)?(#.*)?$/);
  if (!match) return;

  const title = decodeURIComponent(match[1]).replaceAll('_', ' ');
  if (/^(File|Image|Template|Special|User|User blog|Forum|Message Wall|Help):/.test(title)) {
    $(link).replaceWith($(link).contents());
    return;
  }

  const fragment = match[2] ? `#${headingSlug(decodeURIComponent(match[2].slice(1)).replaceAll('_', ' '))}` : '';
  $(link).attr('href', `/${pageSlug(title)}${fragment}`).removeAttr('title').removeAttr('class');
}

// "string_id" -> "String id", for rows whose template gives no label.
const humanize = (source) => source.replaceAll('_', ' ').replace(/^./, (first) => first.toUpperCase());

// A horizontal group labels its cells with a header row above them.
function infoboxLabel($, item) {
  const label = $(item).find('.pi-data-label').text().trim();
  if (label || item.tagName !== 'td') return label || humanize($(item).attr('data-source'));
  const header = $(item).closest('table').find('th').eq($(item).index());
  return header.text().trim() || humanize($(item).attr('data-source'));
}

function infoboxRows($, group) {
  return $(group).find('.pi-data, td[data-source]').toArray().map((item) => {
    const value = $(item).find('.pi-data-value').html() ?? $(item).html();
    return [infoboxLabel($, item), value.trim()];
  }).filter(([, value]) => value);
}

// Consecutive groups without a heading read as one list.
function mergeUntitled(groups) {
  return groups.reduce((merged, group) => {
    const last = merged.at(-1);
    if (last && !last.heading && !group.heading) last.rows.push(...group.rows);
    else merged.push(group);
    return merged;
  }, []);
}

// A portable infobox becomes frontmatter for the Infobox component: loose rows first, then one group per section.
function extractInfobox($) {
  const aside = $('aside.portable-infobox').first();
  if (!aside.length) return undefined;

  const loose = $('<div>').append(aside.children('.pi-data').clone());
  const groups = [{ rows: infoboxRows($, loose) }];
  for (const section of aside.children('section.pi-group').toArray()) {
    groups.push({ heading: $(section).find('.pi-header').first().text().trim() || undefined, rows: infoboxRows($, section) });
  }

  // The title is the infobox heading, so a row repeating it is dropped.
  const title = aside.find('.pi-title').first().text().trim();
  aside.remove();
  for (const group of groups) group.rows = group.rows.filter(([, value]) => cheerio.load(value).text().trim() !== title);
  return { title, groups: mergeUntitled(groups.filter((group) => group.rows.length)) };
}

// A collapsible table becomes a <details>, titled by its one-cell header row when it has one.
function wrapCollapsible($, table) {
  const rows = $(table).children('thead, tbody').children('tr');
  const firstRow = rows.length ? rows.first() : $(table).children('tr').first();
  const caption = firstRow.children().length === 1 ? firstRow.text().trim() : '';
  if (caption) firstRow.remove();

  const details = $('<details class="collapsible">').append($('<summary>').text(caption || 'Show table'));
  if (!$(table).hasClass('mw-collapsed')) details.attr('open', '');
  $(table).removeClass('mw-collapsible mw-collapsed autocollapse').before(details);
  details.append(table);
}

// Every table takes the wiki's table style in place of Fandom's; only sorting survives. Fandom's data attributes go too.
function styleTable($, table) {
  const sortable = $(table).hasClass('sortable');
  for (const name of Object.keys(table.attribs)) if (name !== 'id') $(table).removeAttr(name);
  $(table).attr('class', sortable ? 'wikitable sortable' : 'wikitable');
}

// A footnote that quotes another source at length (a developer post, say), or says it is verbatim, is not the Fandom
// editors' to license: it goes, with the markers that point at it. Ordinary citations are short.
function dropQuotedFootnotes($) {
  $('ol.references > li').each((_, note) => {
    const text = $(note).text();
    if (!/verbatim/i.test(text) && text.split(/\s+/).length <= 60) return;

    const target = `#${$(note).attr('id')}`;
    $('sup.reference').filter((_, mark) => $(mark).find('a').attr('href') === target).remove();
    $(note).remove();
  });
  $('ol.references').filter((_, list) => !$(list).children().length).each((_, list) => {
    $(list).closest('.mw-references-wrap').remove();
    $(list).remove();
  });
}

// Fandom's Quote template is a table: the quote between two cells holding the quotation marks, then an optional row
// naming the speaker. It becomes a quotation with a caption, which the wiki draws as a speech bubble.
function isQuoteTable($, table) {
  const cells = $(table).find('tr').first().children('td');
  return cells.length === 3 && cells.first().text().trim() === '“' && cells.last().text().trim() === '”';
}

function convertQuotes($) {
  $('table').filter((_, table) => isQuoteTable($, table)).each((_, table) => {
    const quote = $(table).find('tr').first().children().eq(1).html().trim();
    if (!quote) return $(table).remove();

    const source = $(table).find('tr').eq(1);
    const speaker = (source.find('cite').html() ?? source.text()).trim().replace(/^[–—-]\s*/, '');
    const caption = speaker ? `<figcaption>${speaker}</figcaption>` : '';
    $(table).replaceWith(`<figure class="quote"><blockquote>${quote}</blockquote>${caption}</figure>`);
  });
}

// Item and book tables show each entry as a picture captioned with its name: the caption stays when the picture goes.
function keepCellCaptions($) {
  $('td figure, th figure').each((_, figure) => {
    const caption = $(figure).find('figcaption');
    if (!caption.text().trim()) return;

    caption.find('p, div').each((_, block) => $(block).replaceWith($(block).contents()));
    $(figure).replaceWith(caption.html().trim());
  });
}

// Fandom's "Loading Screen Tips" box is a table: a heading row, then one row per tip. Each tip becomes the wiki's
// notice box, labelled like the Example page's notice.
function isTipTable($, table) {
  const heading = $(table).find('tr').first().children();
  return heading.length === 1 && /^Loading Screen Tips?$/i.test(heading.text().trim());
}

function convertTips($) {
  $('table').filter((_, table) => isTipTable($, table)).each((_, table) => {
    const tips = $(table).find('tr').slice(1).toArray().map((row) => $(row).children().first().html()?.trim()).filter(Boolean);
    // The talk icon stands in for the label on screen; screen readers still announce it.
    const label = '<span class="loading-tip-label">Loading screen tip:</span>';
    $(table).replaceWith(tips.map((tip) => `<div class="notice loading-tip">${label} ${tip}</div>`).join(''));
  });
}

function cleanHtml(html) {
  const $ = cheerio.load(html, null, false);
  keepCellCaptions($);
  $(removed).remove();
  dropQuotedFootnotes($);
  $('a').each((_, link) => rewriteLink($, link));
  $('[style]').removeAttr('style');
  $('font').each((_, font) => $(font).replaceWith($(font).contents()));
  $('.mw-selflink').each((_, self) => $(self).replaceWith($('<strong>').append($(self).contents())));

  const infobox = extractInfobox($);
  convertQuotes($);
  convertTips($);
  $('table.mw-collapsible').each((_, table) => wrapCollapsible($, table));
  $('table').each((_, table) => styleTable($, table));
  return { $, infobox };
}

function markdownConverter() {
  const turndown = new TurndownService({ headingStyle: 'atx', bulletListMarker: '-', codeBlockStyle: 'fenced' });
  // Tables, collapsed sections, quotes, tip boxes and reference lists keep their HTML: spans, nesting, classes and footnote anchors
  // do not fit Markdown. Blank lines inside would end the HTML block early.
  const hasClass = (node, name) => new RegExp(`\\b${name}\\b`).test(node.getAttribute('class') ?? '');
  const isReferenceList = (node) => node.nodeName === 'OL' && hasClass(node, 'references');
  const isQuote = (node) => node.nodeName === 'FIGURE' && hasClass(node, 'quote');
  const isTip = (node) => node.nodeName === 'DIV' && hasClass(node, 'loading-tip');
  turndown.addRule('html-blocks', {
    filter: (node) => ['TABLE', 'DETAILS'].includes(node.nodeName) || isReferenceList(node) || isQuote(node) || isTip(node),
    replacement: (_, node) => `\n\n${node.outerHTML.replace(/\n\s*\n+/g, '\n')}\n\n`,
  });
  turndown.addRule('footnote-marks', {
    filter: (node) => node.nodeName === 'SUP' && /\breference\b/.test(node.getAttribute('class') ?? ''),
    replacement: (_, node) => node.outerHTML,
  });
  return turndown;
}

function description($) {
  const text = $('p').toArray().map((p) => $(p).text().trim()).find((t) => t.length > 40) ?? '';
  return text.length > 160 ? `${text.slice(0, 157).trimEnd()}…` : text;
}

function frontmatter(page, infobox, summary) {
  const lines = [
    '---',
    `title: ${JSON.stringify(page.title)}`,
    `description: ${JSON.stringify(summary)}`,
    'source:',
    `  title: ${JSON.stringify(page.title)}`,
    `  revision: ${page.revid}`,
    `categories: ${JSON.stringify(page.categories.filter((c) => !c.hidden).map((c) => c.category.replaceAll('_', ' ')))}`,
  ];
  if (infobox?.groups.length) {
    lines.push('infobox:', `  title: ${JSON.stringify(infobox.title)}`, '  groups:');
    for (const group of infobox.groups) {
      lines.push(group.heading ? `    - heading: ${JSON.stringify(group.heading)}` : '    - heading: null', '      rows:');
      for (const row of group.rows) lines.push(`        - ${JSON.stringify(row)}`);
    }
  }
  return [...lines, '---', ''].join('\n');
}

// Two titles that map to one URL would overwrite each other's page.
function claimSlug(slugs, title) {
  const slug = pageSlug(title);
  if (slugs.has(slug) && slugs.get(slug) !== title) throw new Error(`"${title}" and "${slugs.get(slug)}" both map to /${slug}`);
  slugs.set(slug, title);
  return slug;
}

// Pages that reproduce someone else's text word for word are not the Fandom editors' to license, so they are left
// out: Lo-Fi's announcements, transcripts of the game's own dialogue, and the text of its in-game books, which Fandom
// keeps in collapsible boxes. Footnotes are judged one by one in dropQuotedFootnotes; this looks at the article itself.
const wordCount = (text) => text.split(/\s+/).filter(Boolean).length;

function transcribesBook(page, $) {
  if (!page.categories.some((category) => category.category === 'Books')) return false;
  const boxes = $('.mw-collapsible, table').filter((_, box) => !$(box).parents('.mw-collapsible, table').length);
  const boxed = boxes.toArray().reduce((sum, box) => sum + wordCount($(box).text()), 0);
  return boxed * 2 > wordCount($.root().text());
}

function borrowedText(page) {
  if (/\/Dialogue$/.test(page.title)) return "it transcribes the game's dialogue";
  const $ = cheerio.load(page.text);
  $('.references, .mw-references-wrap').remove();
  if (transcribesBook(page, $)) return 'it transcribes an in-game book';
  return /copied verbatim|reproduced verbatim/i.test($.root().text()) ? 'it reproduces another source verbatim' : '';
}

// Paths the site already uses, by its own pages or by hand-written redirects, stay as they are.
async function reservedSlugs() {
  const pages = readdirSync('src/pages').filter((file) => /^[^[].*\.astro$/.test(file)).map((file) => file.replace(/\.astro$/, ''));
  const manual = (await readFile(redirectsFile, 'utf8')).split(redirectsStart)[0];
  const redirected = [...manual.matchAll(/^\/(\S+?)(?:\.html)? /gm)].map((match) => match[1]);
  return new Set([...pages, ...redirected]);
}

async function writePage(page, slug, turndown) {
  const { $, infobox } = cleanHtml(page.text);
  const markdown = turndown.turndown($.html()).replace(/\n{3,}/g, '\n\n').trim();
  const file = `${outDir}/${slug}.md`;
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, `${frontmatter(page, infobox, description($))}\n${markdown}\n`);
}

// Returns the page's redirect rules, or why it was skipped.
async function importPage(title, { turndown, slugs, reserved }) {
  const page = await fetchPage(title);
  const borrowed = borrowedText(page);
  if (borrowed) return { skipped: borrowed };
  if (reserved.has(pageSlug(page.title))) return { skipped: `the site already uses /${pageSlug(page.title)}` };

  const slug = claimSlug(slugs, page.title);
  await writePage(page, slug, turndown);
  const aliases = [...page.aliases, ...(page.redirects ?? []).map((redirect) => redirect.from)];
  const free = aliases.map(pageSlug).filter((alias) => !reserved.has(alias) && alias !== slug);
  return { redirects: free.map((alias) => `/${alias} /${slug} 301`) };
}

// Generated redirects replace everything after the marker line; hand-written rules above it are kept.
// A run over chosen titles adds to the generated rules; a full run replaces them.
async function writeRedirects(lines, partial) {
  const current = existsSync(redirectsFile) ? await readFile(redirectsFile, 'utf8') : '';
  const [manual, generated = ''] = current.split(redirectsStart);
  const kept = partial ? generated.split(/\r?\n/).filter((line) => line.startsWith('/')) : [];
  const rules = [...new Set([...kept, ...lines])].sort();
  await writeFile(redirectsFile, `${manual.trimEnd()}\n\n${redirectsStart}\n${rules.join('\n')}\n`);
}

function report(skipped, failed, imported) {
  for (const [title, reason] of skipped) console.warn(`skipped ${title}: ${reason}`);
  for (const [title, error] of failed) console.error(`failed ${title}: ${error}`);
  console.log(`imported ${imported}, skipped ${skipped.length}, failed ${failed.length}`);
}

async function main() {
  const chosen = process.argv.slice(2);
  await mkdir(cacheDir, { recursive: true });
  await mkdir(outDir, { recursive: true });
  const titles = chosen[0] === '--all' ? await allTitles() : chosen.length ? chosen : testSet;

  const context = { turndown: markdownConverter(), slugs: new Map(), reserved: await reservedSlugs() };
  const redirects = [];
  const skipped = [];
  const failed = [];
  for (const [index, title] of titles.entries()) {
    const result = await importPage(title, context).catch((error) => ({ error: error.message }));
    if (result.redirects) redirects.push(...result.redirects);
    if (result.skipped) skipped.push([title, result.skipped]);
    if (result.error) failed.push([title, result.error]);
    if ((index + 1) % 100 === 0) console.log(`${index + 1} of ${titles.length}`);
  }

  await writeRedirects(redirects, chosen.length > 0 && chosen[0] !== '--all');
  report(skipped, failed, titles.length - skipped.length - failed.length);
}

await main();
