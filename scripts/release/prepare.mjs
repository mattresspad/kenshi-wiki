import assert from 'node:assert/strict';
import {build} from '../ci/build.mjs';
import {gate,cf,git,clean,save,read} from './common.mjs';
import {assertReleaseRun} from './config.mjs';
import {manifest} from './manifest.mjs';
import {auditPackage} from './audit-package.mjs';
const sha=git('rev-parse','HEAD');assertReleaseRun(process.env,sha);clean();
assert.equal(process.env.WIKI_RELEASE_TARGET,'production');assert.equal(process.env.WIKI_EDIT_BRANCH,'main');
const env={WIKI_RELEASE_TARGET:'production',WIKI_EDIT_BRANCH:'main'};
const started=Date.now();
await build('reports/release/build',env);
save('reports/ci/plan.json',{sourceSha:sha,kind:'broad',articleIds:[]});
await gate('reports/release/build','current-routes',['scripts/ci/current.mjs'],env);
await gate('reports/release/build','package-dry-run',[cf,'workers','versions','create','--prebuilt','--dry-run'],env);
const checks=['one production build','current routes, links and provenance','Cloudflare dry run','all-page package checks'];
const candidate=await manifest({checks,validation:{scope:'Preview package; browser smoke follows upload',current:read('reports/ci/current.json').scope}});
await auditPackage(candidate);clean();
save('reports/release/preparation.json',{sourceSha:sha,durationMs:Date.now()-started,checks,builds:1,productionTrafficChanged:false});
console.log('Final package prepared once. Upload and HTTPS smoke checks are the next visible steps.');
